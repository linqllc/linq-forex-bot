#!/usr/bin/env python3
"""Run a LINQ research experiment grid from a prediction CSV."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from linq_platform.research.experiment_grid import (
    ExperimentGridConfig,
    run_experiment_grid,
)


def parse_float_list(value: str) -> tuple[float, ...]:
    return tuple(float(item.strip()) for item in value.split(",") if item.strip())


def parse_optional_float_list(
    value: str,
) -> tuple[float | None, ...]:
    values: list[float | None] = []

    for item in value.split(","):
        normalized = item.strip().lower()

        if not normalized:
            continue

        if normalized in {"none", "all", "unlimited"}:
            values.append(None)
        else:
            values.append(float(normalized))

    return tuple(values)


def parse_string_list(value: str) -> tuple[str, ...]:
    return tuple(item.strip().lower() for item in value.split(",") if item.strip())


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate probability thresholds, sessions, and spread limits "
            "against scored holdout predictions."
        )
    )

    parser.add_argument(
        "predictions",
        type=Path,
        help="Prediction CSV generated by the native research pipeline.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("reports/experiment_grid"),
    )
    parser.add_argument(
        "--thresholds",
        default="0.50,0.55,0.60,0.65,0.70,0.75,0.80,0.85,0.90",
    )
    parser.add_argument(
        "--sessions",
        default="all",
        help="Comma-separated values such as all,london,new_york,asia.",
    )
    parser.add_argument(
        "--maximum-spreads",
        default="none",
        help="Comma-separated limits such as none,2.0,1.5,1.0.",
    )
    parser.add_argument(
        "--minimum-trades",
        type=int,
        default=10,
    )

    return parser


def main() -> None:
    args = build_parser().parse_args()

    predictions = pd.read_csv(args.predictions)

    config = ExperimentGridConfig(
        thresholds=parse_float_list(args.thresholds),
        sessions=parse_string_list(args.sessions),
        maximum_spreads=parse_optional_float_list(args.maximum_spreads),
        minimum_trades=args.minimum_trades,
    )

    leaderboard = run_experiment_grid(
        predictions,
        config,
    )

    args.output.mkdir(
        parents=True,
        exist_ok=True,
    )

    csv_path = args.output / "experiment_leaderboard.csv"
    json_path = args.output / "experiment_leaderboard.json"

    leaderboard.to_csv(
        csv_path,
        index=False,
    )

    payload = {
        "predictions_file": str(args.predictions),
        "thresholds": list(config.thresholds),
        "sessions": list(config.sessions),
        "maximum_spreads": list(config.maximum_spreads),
        "minimum_trades": config.minimum_trades,
        "experiments": leaderboard.to_dict(orient="records"),
    }

    json_path.write_text(
        json.dumps(
            payload,
            indent=2,
            default=str,
        ),
        encoding="utf-8",
    )

    eligible = leaderboard.loc[leaderboard["eligible"]]

    print("=" * 72)
    print("LINQ RESEARCH ENGINE V3")
    print("=" * 72)
    print(f"Experiments evaluated: {len(leaderboard)}")
    print(f"Eligible experiments:  {len(eligible)}")
    print(f"CSV leaderboard:       {csv_path}")
    print(f"JSON leaderboard:      {json_path}")

    if not eligible.empty:
        print()
        print("TOP EXPERIMENTS")
        print(eligible.head(10).to_string(index=False))


if __name__ == "__main__":
    main()
